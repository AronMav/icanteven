export function wordLabel(count: number): string {
  const lastTwo = count % 100;
  const last = count % 10;
  const ending = lastTwo >= 11 && lastTwo <= 14 ? 'слов' : last === 1 ? 'слово' : last >= 2 && last <= 4 ? 'слова' : 'слов';
  return `${count.toLocaleString('ru-RU')} ${ending}`;
}
